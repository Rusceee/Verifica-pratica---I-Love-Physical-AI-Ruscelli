class Componente:
        def __init__(self, codice: str, nome: str, peso_kg: float) -> None:
            this.codice=codice
            this.nome=nome
            this.peso_kg=peso_kg
        def get_codice(self):
            return this.codice
        def get_nome(self):
            return this.nome
        def get_peso_kg(self):
            return this.peso_kg